#!/usr/bin/env python3
"""
Alpaca Paper Trading Connector for Quality Momentum Strategy

Integrates with Alpaca's paper trading API to execute signals generated by the strategy.
Handles order placement, portfolio synchronization, and position tracking.

Key Features:
- Paper trading execution with Alpaca API
- Real-time portfolio synchronization
- Order management and tracking
- Risk controls and position sizing
"""

import os
import sys
import json
import time
import logging
from datetime import datetime, timedelta
from typing import Dict, List, Optional, Tuple
import pandas as pd

try:
    import alpaca_trade_api as tradeapi
    from alpaca_trade_api.rest import APIError
    ALPACA_AVAILABLE = True
except ImportError:
    ALPACA_AVAILABLE = False
    print("⚠️ Alpaca Trade API not installed. Install with: pip install alpaca-trade-api")

# Add src to path for imports
current_dir = os.path.dirname(os.path.abspath(__file__))
project_root = os.path.dirname(os.path.dirname(current_dir))
sys.path.insert(0, os.path.join(project_root, 'src'))

class AlpacaPaperTrader:
    """
    Alpaca paper trading connector for the Quality Momentum Strategy.
    """
    
    def __init__(self, config_file: str = None):
        """Initialize Alpaca connection with paper trading credentials."""
        if not ALPACA_AVAILABLE:
            raise ImportError("Alpaca Trade API not available. Please install alpaca-trade-api.")
        
        self.config = self._load_config(config_file)
        self.setup_logging()
        
        # Initialize Alpaca API (Paper Trading)
        self.api = tradeapi.REST(
            key_id=self.config['alpaca_api_key'],
            secret_key=self.config['alpaca_secret_key'],
            base_url=self.config.get('alpaca_base_url', 'https://paper-api.alpaca.markets'),
            api_version='v2'
        )
        
        # Trading parameters
        self.min_order_value = self.config.get('min_order_value', 100)  # $100 minimum
        self.max_order_value = self.config.get('max_order_value', 10000)  # $10k maximum
        self.order_timeout = self.config.get('order_timeout', 300)  # 5 minutes
        
        # Verify connection
        self._verify_connection()
    
    def _load_config(self, config_file: str) -> Dict:
        """Load Alpaca API configuration."""
        # Default configuration
        default_config = {
            'alpaca_base_url': 'https://paper-api.alpaca.markets',
            'min_order_value': 100,
            'max_order_value': 10000,
            'order_timeout': 300,
            'max_positions': 50,
            'cash_buffer': 0.05
        }
        
        # Load from config file if provided
        if config_file and os.path.exists(config_file):
            with open(config_file, 'r') as f:
                user_config = json.load(f)
                default_config.update(user_config)
        
        # Load from environment variables
        default_config['alpaca_api_key'] = os.getenv('ALPACA_API_KEY')
        default_config['alpaca_secret_key'] = os.getenv('ALPACA_SECRET_KEY')
        
        if not default_config['alpaca_api_key'] or not default_config['alpaca_secret_key']:
            raise ValueError("Alpaca API credentials not found. Set ALPACA_API_KEY and ALPACA_SECRET_KEY environment variables.")
        
        return default_config
    
    def setup_logging(self):
        """Setup logging configuration."""
        logging.basicConfig(
            level=logging.INFO,
            format='%(asctime)s - %(name)s - %(levelname)s - %(message)s',
            handlers=[
                logging.FileHandler(os.path.join(project_root, 'logs', 'alpaca_trading.log')),
                logging.StreamHandler()
            ]
        )
        self.logger = logging.getLogger(__name__)
    
    def _verify_connection(self):
        """Verify Alpaca API connection."""
        try:
            account = self.api.get_account()
            self.logger.info(f"Connected to Alpaca Paper Trading")
            self.logger.info(f"Account Status: {account.status}")
            self.logger.info(f"Portfolio Value: ${float(account.portfolio_value):,.2f}")
            self.logger.info(f"Buying Power: ${float(account.buying_power):,.2f}")
            
            if account.status != 'ACTIVE':
                raise ValueError(f"Account status is not ACTIVE: {account.status}")
                
        except Exception as e:
            self.logger.error(f"Failed to connect to Alpaca: {e}")
            raise
    
    def get_account_info(self) -> Dict:
        """Get current account information."""
        try:
            account = self.api.get_account()
            return {
                'portfolio_value': float(account.portfolio_value),
                'buying_power': float(account.buying_power),
                'cash': float(account.cash),
                'market_value': float(account.long_market_value),
                'status': account.status,
                'day_trades': getattr(account, 'daytrade_count', 0)  # not present in newer API versions
            }
        except Exception as e:
            self.logger.error(f"Error getting account info: {e}")
            return {}
    
    def get_current_positions(self) -> Dict[str, Dict]:
        """Get current portfolio positions."""
        try:
            positions = self.api.list_positions()
            portfolio = {}
            
            account_info = self.get_account_info()
            total_value = account_info.get('portfolio_value', 1)
            
            for position in positions:
                portfolio[position.symbol] = {
                    'shares': int(position.qty),
                    'market_value': float(position.market_value),
                    'weight': float(position.market_value) / total_value,
                    'avg_entry_price': float(position.avg_entry_price),
                    'current_price': float(position.current_price),
                    'unrealized_pl': float(position.unrealized_pl),
                    'unrealized_plpc': float(position.unrealized_plpc)
                }
            
            self.logger.info(f"Retrieved {len(portfolio)} positions")
            return portfolio
            
        except Exception as e:
            self.logger.error(f"Error getting positions: {e}")
            return {}
    
    def get_market_price(self, symbol: str) -> Optional[float]:
        """Get current market price for a symbol."""
        try:
            # Get latest quote
            quote = self.api.get_latest_quote(symbol)
            
            # Use mid-price (average of bid and ask)
            if hasattr(quote, 'bid_price') and hasattr(quote, 'ask_price'):
                if quote.bid_price and quote.ask_price:
                    return (quote.bid_price + quote.ask_price) / 2
                elif quote.bid_price:
                    return quote.bid_price
                elif quote.ask_price:
                    return quote.ask_price
            
            # Fallback to last trade price
            trade = self.api.get_latest_trade(symbol)
            if trade and hasattr(trade, 'price'):
                return trade.price
                
            return None
            
        except Exception as e:
            self.logger.warning(f"Error getting price for {symbol}: {e}")
            return None
    
    def calculate_order_quantity(self, symbol: str, target_weight: float, portfolio_value: float) -> Tuple[int, str]:
        """Calculate order quantity based on target weight."""
        try:
            # Get current price
            price = self.get_market_price(symbol)
            if not price:
                return 0, "No price available"
            
            # Calculate target dollar value
            target_value = target_weight * portfolio_value
            
            # Check minimum order value
            if target_value < self.min_order_value:
                return 0, f"Target value ${target_value:.2f} below minimum ${self.min_order_value}"
            
            # Check maximum order value
            if target_value > self.max_order_value:
                target_value = self.max_order_value
                self.logger.warning(f"Capping {symbol} order at ${self.max_order_value}")
            
            # Calculate shares (rounded down to avoid over-allocation)
            shares = int(target_value / price)
            
            if shares <= 0:
                return 0, "Insufficient funds for minimum share"
            
            actual_value = shares * price
            self.logger.info(f"{symbol}: Target ${target_value:.2f}, Actual ${actual_value:.2f} ({shares} shares @ ${price:.2f})")
            
            return shares, "OK"
            
        except Exception as e:
            self.logger.error(f"Error calculating quantity for {symbol}: {e}")
            return 0, str(e)
    
    def place_order(self, symbol: str, action: str, quantity: int, order_type: str = 'market') -> Optional[str]:
        """Place a trading order."""
        try:
            if quantity <= 0:
                self.logger.warning(f"Invalid quantity {quantity} for {symbol}")
                return None
            
            # Determine side
            side = 'buy' if action in ['BUY', 'INCREASE'] else 'sell'
            
            # Place order
            order = self.api.submit_order(
                symbol=symbol,
                qty=quantity,
                side=side,
                type=order_type,
                time_in_force='day'
            )
            
            self.logger.info(f"Order placed: {side.upper()} {quantity} {symbol} (Order ID: {order.id})")
            return order.id
            
        except APIError as e:
            self.logger.error(f"Alpaca API error placing order for {symbol}: {e}")
            return None
        except Exception as e:
            self.logger.error(f"Error placing order for {symbol}: {e}")
            return None
    
    def execute_signals(self, signals: Dict[str, Dict]) -> Dict[str, str]:
        """Execute trading signals."""
        self.logger.info(f"Executing {len(signals)} signals...")
        
        results = {}
        account_info = self.get_account_info()
        portfolio_value = account_info.get('portfolio_value', 0)
        
        if portfolio_value <= 0:
            self.logger.error("Invalid portfolio value")
            return results
        
        # Get current positions
        current_positions = self.get_current_positions()
        
        # Sort signals by action (sells first, then buys)
        sell_signals = {k: v for k, v in signals.items() if v['action'] in ['SELL', 'REDUCE']}
        buy_signals = {k: v for k, v in signals.items() if v['action'] in ['BUY', 'INCREASE']}
        
        # Execute sell orders first
        for symbol, signal in sell_signals.items():
            try:
                current_pos = current_positions.get(symbol, {})
                current_shares = current_pos.get('shares', 0)
                
                if current_shares <= 0:
                    results[symbol] = "No position to sell"
                    continue
                
                if signal['action'] == 'SELL':
                    # Sell entire position
                    quantity = current_shares
                else:  # REDUCE
                    # Calculate shares to reduce
                    target_shares, calc_msg = self.calculate_order_quantity(
                        symbol, signal['target_weight'], portfolio_value)
                    quantity = current_shares - target_shares
                
                if quantity > 0:
                    order_id = self.place_order(symbol, signal['action'], quantity)
                    results[symbol] = f"Sell order placed: {order_id}" if order_id else "Sell order failed"
                else:
                    results[symbol] = "No reduction needed"
                    
            except Exception as e:
                results[symbol] = f"Error: {e}"
                self.logger.error(f"Error executing sell signal for {symbol}: {e}")
        
        # Wait a moment for sell orders to process
        time.sleep(2)
        
        # Execute buy orders
        for symbol, signal in buy_signals.items():
            try:
                current_pos = current_positions.get(symbol, {})
                current_shares = current_pos.get('shares', 0)
                
                # Calculate target shares
                target_shares, calc_msg = self.calculate_order_quantity(
                    symbol, signal['target_weight'], portfolio_value)
                
                if calc_msg != "OK":
                    results[symbol] = calc_msg
                    continue
                
                if signal['action'] == 'BUY':
                    # Buy new position
                    quantity = target_shares
                else:  # INCREASE
                    # Add to existing position
                    quantity = target_shares - current_shares
                
                if quantity > 0:
                    order_id = self.place_order(symbol, signal['action'], quantity)
                    results[symbol] = f"Buy order placed: {order_id}" if order_id else "Buy order failed"
                else:
                    results[symbol] = "No purchase needed"
                    
            except Exception as e:
                results[symbol] = f"Error: {e}"
                self.logger.error(f"Error executing buy signal for {symbol}: {e}")
        
        # Summary
        successful_orders = sum(1 for r in results.values() if "placed" in r)
        self.logger.info(f"Signal execution complete: {successful_orders}/{len(signals)} orders placed")
        
        return results
    
    def monitor_orders(self, timeout_minutes: int = 30) -> Dict[str, str]:
        """Monitor open orders and return status."""
        try:
            orders = self.api.list_orders(status='open')
            
            if not orders:
                self.logger.info("No open orders to monitor")
                return {}
            
            self.logger.info(f"Monitoring {len(orders)} open orders...")
            
            start_time = datetime.now()
            timeout = timedelta(minutes=timeout_minutes)
            
            order_status = {}
            
            while datetime.now() - start_time < timeout:
                for order in orders:
                    if order.id not in order_status:
                        updated_order = self.api.get_order(order.id)
                        
                        if updated_order.status in ['filled', 'canceled', 'rejected']:
                            order_status[order.id] = {
                                'symbol': updated_order.symbol,
                                'status': updated_order.status,
                                'filled_qty': updated_order.filled_qty,
                                'filled_avg_price': updated_order.filled_avg_price
                            }
                            
                            self.logger.info(f"Order {order.id} ({updated_order.symbol}): {updated_order.status}")
                
                # Check if all orders are complete
                if len(order_status) == len(orders):
                    break
                
                time.sleep(10)  # Check every 10 seconds
            
            return order_status
            
        except Exception as e:
            self.logger.error(f"Error monitoring orders: {e}")
            return {}
    
    def get_portfolio_summary(self) -> Dict:
        """Get comprehensive portfolio summary."""
        try:
            account_info = self.get_account_info()
            positions = self.get_current_positions()
            
            # Calculate sector allocation
            sector_allocation = {}
            style_allocation = {}
            
            total_positions = len(positions)
            total_market_value = sum(pos['market_value'] for pos in positions.values())
            
            summary = {
                'account_info': account_info,
                'total_positions': total_positions,
                'total_market_value': total_market_value,
                'cash_percentage': account_info.get('cash', 0) / account_info.get('portfolio_value', 1),
                'top_positions': sorted(positions.items(), 
                                      key=lambda x: x[1]['market_value'], reverse=True)[:10],
                'positions': positions
            }
            
            return summary
            
        except Exception as e:
            self.logger.error(f"Error getting portfolio summary: {e}")
            return {}

